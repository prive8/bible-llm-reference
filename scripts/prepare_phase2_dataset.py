# ---------------------------------------------------------------------------
# Seed examples: generated from cross-reference triples
# ---------------------------------------------------------------------------

def load_cross_references() -> dict:
    """Load cross-references JSON. Returns empty dict on miss.

    Actual structure: {"metadata": {...}, "outgoing": {citation: [{"to": X, "votes": N}, ...]}}
    Returns just the outgoing dict for convenience.
    """
    if not REFERENCES_FILE.exists():
        print(f"Warning: {REFERENCES_FILE} not found, seed mode will be empty")
        return {}
    with open(REFERENCES_FILE, "r", encoding="utf-8") as f:
        data = json.load(f)
    return data.get("outgoing", {})


def build_seed_examples(min_votes: int = 50, limit: int = 1000) -> list[dict]:
    """Build seed training examples from cross-reference triples.

    For each (source_verse, target_verse, votes) edge above min_votes,
    emit a teaching-style example that asks "How does <source> relate to
    <target>?" — Phase 2 work would replace this with actual model-
    generated answers on the same substrate.

    Edge dict shape: {"to": "X Y:Z", "votes": N}
    """
    xrefs = load_cross_references()
    if not xrefs:
        return []

    # xrefs structure: {source_citation: [{"votes": N, "to": "X Y:Z"}, ...]}
    examples = []
    for source, edges in xrefs.items():
        for edge in edges:
            votes = edge.get("votes", 0)
            target = edge.get("to", "")
            if not target:
                continue
            if votes < min_votes:
                continue
            # Pick a voice based on which corpus the citation is in.
            # Heuristic: if "Quran" in target, islam; if Hebrew book, judaism;
            # otherwise christianity.
            if target.startswith("Quran "):
                tradition, voice = "islam", "qari_sunni"
            elif any(target.startswith(b + " ") for b in (
                "Genesis", "Exodus", "Leviticus", "Numbers", "Deuteronomy",
                "Joshua", "Judges", "Samuel", "Kings", "Isaiah", "Jeremiah",
                "Ezekiel", "Psalms", "Proverbs", "Job",
            )):
                tradition, voice = "judaism", "rabbi_orthodox"
            else:
                tradition, voice = "christianity", "pastor_evangelical"

            example = {
                "messages": [
                    {
                        "role": "system",
                        "content": build_system_prompt(tradition, voice),
                    },
                    {
                        "role": "user",
                        "content": (
                            f"How does {source} relate to {target}? "
                            "What themes do they share?"
                        ),
                    },
                    {
                        "role": "assistant",
                        "content": (
                            f"[Phase 2 placeholder — replace with model-generated "
                            f"answer that cites both {source} and {target}, "
                            f"drawing on the retrieval substrate for grounding. "
                            f"Cross-reference weight: {votes} votes.]"
                        ),
                    },
                ],
                "metadata": {
                    "tradition": tradition,
                    "voice": voice,
                    "primary_citation": source,
                    "secondary_citations": [target],
                    "source": f"cross_references:{source}:{target}",
                    "votes": votes,
                },
            }
            examples.append(example)
            if len(examples) >= limit:
                return examples
    return examples


# ---------------------------------------------------------------------------
# Mode handlers
# ---------------------------------------------------------------------------

def mode_sample(output_path: Path) -> None:
    """Write the 3 hand-curated sample examples to JSONL."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        for ex in SAMPLE_EXAMPLES:
            f.write(json.dumps(ex, ensure_ascii=False) + "\n")
    print(f"Wrote {len(SAMPLE_EXAMPLES)} sample examples to {output_path}")


def mode_seed(output_path: Path, min_votes: int, limit: int) -> None:
    """Write seed examples derived from cross-references."""
    examples = build_seed_examples(min_votes=min_votes, limit=limit)
    if not examples:
        print("No seed examples generated (cross-references empty or below threshold)")
        return
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        for ex in examples:
            f.write(json.dumps(ex, ensure_ascii=False) + "\n")
    print(f"Wrote {len(examples)} seed examples to {output_path}")
    print(f"  (min_votes={min_votes}, limit={limit})")
    by_tradition: dict[str, int] = {}
    for ex in examples:
        t = ex["metadata"]["tradition"]
        by_tradition[t] = by_tradition.get(t, 0) + 1
    print(f"  by tradition: {by_tradition}")


def mode_stats() -> None:
    """Print dataset statistics without writing a file."""
    xrefs = load_cross_references()
    if xrefs:
        total_edges = sum(len(v) for v in xrefs.values())
        print(f"cross-references: {len(xrefs)} source verses, {total_edges} total edges")
    else:
        print("cross-references: (not loaded)")
    print(f"voice taxonomy: {sum(len(v) for v in VOICE_TAXONOMY.values())} voices across "
          f"{len(VOICE_TAXONOMY)} traditions")
    for trad, voices in VOICE_TAXONOMY.items():
        print(f"  {trad}: {list(voices.keys())}")
    print(f"sample examples: {len(SAMPLE_EXAMPLES)}")


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(
        description="Phase 2 fine-tune dataset preparation (ADR-012)"
    )
    parser.add_argument(
        "--mode",
        choices=["sample", "seed", "stats"],
        required=True,
        help="sample: 3 hand-curated examples; seed: from cross-references; stats: just print"
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=PHASE2_DATA_DIR / "output.jsonl",
        help="Output JSONL path (default: data/phase2/output.jsonl)"
    )
    parser.add_argument(
        "--min-votes",
        type=int,
        default=50,
        help="Min cross-reference votes for seed mode (default: 50)"
    )
    parser.add_argument(
        "--limit",
        type=int,
        default=1000,
        help="Max seed examples (default: 1000)"
    )
    args = parser.parse_args()

    if args.mode == "sample":
        mode_sample(args.output)
    elif args.mode == "seed":
        mode_seed(args.output, args.min_votes, args.limit)
    elif args.mode == "stats":
        mode_stats()


if __name__ == "__main__":
    main()
