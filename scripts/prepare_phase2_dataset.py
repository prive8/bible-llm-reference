# ---------------------------------------------------------------------------
# Seed examples: generated from cross-reference triples
# ---------------------------------------------------------------------------

def load_cross_references() -> dict:
    """Load cross-references JSON. Returns empty dict on miss.

    Actual structure: {"metadata": {...}, "outgoing": {citation: [{"to": X, "votes": N}, ...]}}
    Returns just the outgoing dict for convenience.
    """
    if not REFERENCES_FILE.exists():
        print(f"Warning: {REFERENCES_FILE} not found, seed mode will be empty")
        return {}
    with open(REFERENCES_FILE, "r", encoding="utf-8") as f:
        data = json.load(f)
    return data.get("outgoing", {})


def build_seed_examples(min_votes: int = 50, limit: int = 1000) -> list[dict]:
    """Build seed training examples from cross-reference triples.

    For each (source_verse, target_verse, votes) edge above min_votes,
    emit a teaching-style example that asks "How does <source> relate to
    <target>?" — Phase 2 work would replace this with actual model-
    generated answers on the same substrate.

    Edge dict shape: {"to": "X Y:Z", "votes": N}
    """
    xrefs = load_cross_references()
    if not xrefs:
        return []

    # xrefs structure: {source_citation: [{"votes": N, "to": "X Y:Z"}, ...]}
    examples = []
    for source, edges in xrefs.items():
        for edge in edges:
            votes = edge.get("votes", 0)
            target = edge.get("to", "")
            if not target:
                continue
            if votes < min_votes:
                continue
            # Pick a voice based on which corpus the citation is in.
            # Heuristic: if "Quran" in target, islam; if Hebrew book, judaism;
            # otherwise christianity.
            if target.startswith("Quran "):
                tradition, voice = "islam", "qari_sunni"
            elif any(target.startswith(b + " ") for b in (
                "Genesis", "Exodus", "Leviticus", "Numbers", "Deuteronomy",
                "Joshua", "Judges", "Samuel", "Kings", "Isaiah", "Jeremiah",
                "Ezekiel", "Psalms", "Proverbs", "Job",
            )):
                tradition, voice = "judaism", "rabbi_orthodox"
            else:
                tradition, voice = "christianity", "pastor_evangelical"

            example = {
                "messages": [
                    {
                        "role": "system",
                        "content": build_system_prompt(tradition, voice),
                    },
                    {
                        "role": "user",
                        "content": (
                            f"How does {source} relate to {target}? "
                            "What themes do they share?"
                        ),
                    },
                    {
                        "role": "assistant",
                        "content": (
                            f"[Phase 2 placeholder — replace with model-generated "
                            f"answer that cites both {source} and {target}, "
                            f"drawing on the retrieval substrate for grounding. "
                            f"Cross-reference weight: {votes} votes.]"
                        ),
                    },
                ],
                "metadata": {
                    "tradition": tradition,
                    "voice": voice,
                    "primary_citation": source,
                    "secondary_citations": [target],
                    "source": f"cross_references:{source}:{target}",
                    "votes": votes,
                },
            }
            examples.append(example)
            if len(examples) >= limit:
                return examples
    return examples


