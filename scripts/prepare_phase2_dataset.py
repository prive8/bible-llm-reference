#!/usr/bin/env python3
"""Phase 2 fine-tune dataset preparation (ADR-012).

Exports the bible-llm-reference retrieval substrate (corpus + cross-refs
+ Strong's) into a JSONL format suitable for fine-tuning a Phase 2
generative model. Per HANDOFF §1, Phase 2 is "generative voice
fine-tune — a tool that takes a question and writes a response in
the voice of the tradition (pastor citing Romans, rabbi citing Rashi,
qari citing tafsir), grounded in the corpus, always with citations,
never inventing doctrine."

This script does NOT train anything — it defines the *shape* of the
training data so the actual fine-tuning work in Phase 2 has a clear
starting point. Output goes to `data/phase2/` (gitignored; derived).

Per ADR-012 (Llama-3.1-8B-Instruct pick), the dataset format is
designed for an OpenAI-style instruction-tuning JSONL that QLoRA
recipes can consume directly.

Usage:
    # Generate sample examples (sanity check the format)
    python3 scripts/prepare_phase2_dataset.py --mode sample --output data/phase2/sample.jsonl

    # Generate the full seed dataset from existing corpus + cross-refs
    python3 scripts/prepare_phase2_dataset.py --mode seed --output data/phase2/seed.jsonl

    # Print dataset statistics (no file written)
    python3 scripts/prepare_phase2_dataset.py --mode stats

The "seed" mode generates synthetic training examples from
cross-reference triples: for each (source verse, target verse) pair
in `data/references/cross_references.json`, we emit an example of the
form "How does <source> relate to <target>?" with a teaching-style
answer that names both citations. This is a *seed* dataset — Phase 2
work would replace it with self-distilled examples generated by a
stronger model on the same substrate.

Stdlib-only.
"""

